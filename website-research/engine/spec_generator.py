"""
Design Specification Generator
Generates full 16-part specifications for client projects based on researched references.
"""

import datetime

class SpecGenerator:
    def __init__(self, storage_manager):
        self.storage = storage_manager

    def generate_specification(self, project_data, selected_references, design_system=None):
        project_name = project_data.get("name", "Client Website Project")
        industry = project_data.get("industry", "General")
        target_audience = project_data.get("target_audience", "Prospective Customers & Clients")
        goals = project_data.get("goals", "Modern, high-converting digital presence.")
        
        # Fallback design system defaults if not explicitly specified
        ds = design_system or {}
        colors = ds.get("colors", {
            "primary": "#1E293B",
            "secondary": "#475569",
            "accent": "#2563EB",
            "background": "#F8FAFC",
            "surface": "#FFFFFF",
            "text_primary": "#0F172A",
            "text_muted": "#64748B"
        })
        typography = ds.get("typography", {
            "display": "Cormorant Garamond, serif",
            "heading": "Plus Jakarta Sans, sans-serif",
            "body": "Inter, sans-serif",
            "mono": "JetBrains Mono, monospace"
        })
        
        lines = []
        lines.append(f"# Website Design Specification: {project_name}")
        lines.append(f"**Generated by Unified Design Intelligence System** | Date: {datetime.date.today().isoformat()}\n")
        
        # 1. Project Overview
        lines.append("## 1. Project Overview")
        lines.append(f"- **Client / Project Name**: {project_name}")
        lines.append(f"- **Target Industry**: {industry}")
        lines.append(f"- **Target Audience**: {target_audience}")
        lines.append(f"- **Primary Strategic Goal**: {goals}")
        lines.append("- **Development Scope**: Multi-section responsive modern web application.\n")
        
        # 2. Selected Reference Websites
        lines.append("## 2. Selected Reference Websites")
        lines.append("The following curated references were analyzed and selected to inform the visual, layout, and UX strategy:")
        for idx, ref in enumerate(selected_references, 1):
            name = ref.get("name", f"Reference {idx}")
            platform = ref.get("source_platform", "Curated Gallery")
            score = ref.get("rank_score", "N/A")
            rationale = ref.get("selection_rationale", "High visual quality and relevant layout structure.")
            lines.append(f"{idx}. **{name}** (via {platform}) — *Score: {score}*")
            lines.append(f"   - **Why Selected**: {rationale}")
        lines.append("")

        # 3. Reference URLs
        lines.append("## 3. Reference URLs")
        lines.append("| Reference | Platform | Research / Gallery Link | Live Site URL |")
        lines.append("| :--- | :--- | :--- | :--- |")
        for ref in selected_references:
            name = ref.get("name", "Site")
            platform = ref.get("source_platform", "Web")
            source_url = ref.get("source_url", "#")
            live_url = ref.get("live_url", source_url)
            lines.append(f"| {name} | {platform} | [{source_url}]({source_url}) | [{live_url}]({live_url}) |")
        lines.append("")

        # 4. Screenshot References
        lines.append("## 4. Screenshot References")
        lines.append("Screenshots captured and stored in the local intelligence repository:")
        for ref in selected_references:
            name = ref.get("name", "Site")
            screens = ref.get("screenshots", {})
            desktop = screens.get("desktop")
            mobile = screens.get("mobile")
            lines.append(f"### {name}")
            if desktop:
                lines.append(f"- **Desktop Layout**: `[desktop_view]({desktop})`")
            if mobile:
                lines.append(f"- **Mobile Layout**: `[mobile_view]({mobile})`")
            if not desktop and not mobile:
                lines.append("- *Live interactive inspection performed via Browser MCP.*")
            lines.append("")

        # 5. Design Direction
        lines.append("## 5. Design Direction")
        lines.append(f"- **Aesthetic Theme**: {ds.get('theme', 'Editorial Modernity with Clean High-Contrast Hierarchy')}.")
        lines.append("- **Tone of Voice**: Sophisticated, trustworthy, intuitive, and conversion-focused.")
        lines.append("- **Visual Balance**: Generous whitespace with deliberate focal points, avoiding cluttered generic template patterns.")
        lines.append("- **Originality Note**: Incorporates the proven UX flows from references while using custom visual assets, proprietary layout styling, and distinct branding.\n")

        # 6. Color Palette with HEX Codes
        lines.append("## 6. Color Palette (Strict Hex System)")
        lines.append("| Role | Color Name | HEX Code | Usage |")
        lines.append("| :--- | :--- | :--- | :--- |")
        for role, hex_code in colors.items():
            lines.append(f"| `{role}` | Branded {role.title()} | `{hex_code}` | Core {role} application |")
        lines.append("\n> [!NOTE]\n> All color combinations meet WCAG 2.1 AA standards (minimum 4.5:1 contrast for body text).\n")

        # 7. Typography System
        lines.append("## 7. Typography System")
        lines.append(f"- **Display Font**: `{typography.get('display')}` — Hero headlines & prominent statements.")
        lines.append(f"- **Heading Font**: `{typography.get('heading')}` — Section headings (H1-H3).")
        lines.append(f"- **Body Font**: `{typography.get('body')}` — Paragraphs, UI labels, descriptions.")
        lines.append(f"- **Monospace Font**: `{typography.get('mono')}` — Metrics, data badges, code blocks.")
        lines.append("- **Type Scale** (Major Third 1.25):")
        lines.append("  - H1 / Display: `3.5rem` / `56px` (Line height: 1.1, Letter spacing: `-0.02em`)")
        lines.append("  - H2: `2.5rem` / `40px` (Line height: 1.2, Letter spacing: `-0.015em`)")
        lines.append("  - H3: `1.75rem` / `28px` (Line height: 1.3)")
        lines.append("  - Body Regular: `1.0rem` / `16px` (Line height: 1.6)")
        lines.append("  - Small / Caption: `0.875rem` / `14px` (Line height: 1.5)\n")

        # 8. Spacing System
        lines.append("## 8. Spacing & Spatial System")
        lines.append("- **Base Unit**: 8-point spatial grid (`4px`, `8px`, `16px`, `24px`, `32px`, `48px`, `64px`, `96px`, `128px`).")
        lines.append("- **Container Width**: Max `1280px` centered with auto margins.")
        lines.append("- **Gutter Width**: `24px` on desktop, `16px` on mobile.")
        lines.append("- **Section Vertical Padding**: `80px` to `120px` desktop, `48px` to `64px` mobile.\n")

        # 9. Component Specifications
        lines.append("## 9. Component Specifications")
        lines.append("1. **Hero Component**: High-impact value proposition, clear primary action button, ambient imagery/media, and social proof trust badges.")
        lines.append("2. **Navigation Bar**: Sticky/glassmorphic header with logo, primary navigation links, direct CTA button, and accessible mobile hamburger trigger.")
        lines.append("3. **Feature / Service Cards**: Clean borders (`1px solid rgba(226, 232, 240, 0.8)`), subtle corner radius (`12px` to `16px`), icon/badge, title, description, and hover elevation.")
        lines.append("4. **Pricing / Catalog Grid**: Clear tier differentiation, highlighted 'Most Popular' badge, feature checklists with check icons, and high-visibility signup button.")
        lines.append("5. **Testimonial Carousel / Grid**: Quotation mark accent, client avatar, name, verified title/company, and rating stars.")
        lines.append("6. **Conversion CTA Banner**: High-contrast background with focal heading, concise copy, and frictionless input/booking trigger.")
        lines.append("7. **Footer Module**: Brand logo, mission summary, navigation sitemap columns, social icons, newsletter form, copyright, and legal links.\n")

        # 10. Navigation Structure
        lines.append("## 10. Navigation Structure & Site Architecture")
        lines.append("```mermaid")
        lines.append("flowchart TD")
        lines.append('  Home["Home Page (Primary Showcase)"]')
        lines.append('  Hero["Hero Section"]')
        lines.append('  Features["Services / Offerings"]')
        lines.append('  Showcase["Portfolio / Menu / Catalog"]')
        lines.append('  Proof["Reviews & Social Proof"]')
        lines.append('  Contact["Direct Booking / Inquiries"]')
        lines.append("  Home --> Hero --> Features --> Showcase --> Proof --> Contact")
        lines.append("```\n")

        # 11. Page Layouts
        lines.append("## 11. Page Layouts & Flow")
        lines.append("- **Section Sequence**:")
        lines.append("  1. Sticky Navigation Header")
        lines.append("  2. Full-Bleed Hero Section with Dual CTA")
        lines.append("  3. Trust & Social Proof Logo Wall")
        lines.append("  4. Core Offerings / Services Grid (3-column desktop, 1-column mobile)")
        lines.append("  5. Interactive Showcase / Menu / Gallery Module")
        lines.append("  6. Social Proof & Verified Testimonials")
        lines.append("  7. FAQ / Detailed Information Accordion")
        lines.append("  8. Final Conversion CTA Card")
        lines.append("  9. Comprehensive Multi-column Footer\n")

        # 12. Responsive Requirements
        lines.append("## 12. Responsive Requirements")
        lines.append("- **Breakpoints**:")
        lines.append("  - Mobile: `< 640px` (Single column, full width cards, off-canvas navigation drawer)")
        lines.append("  - Tablet: `640px - 1024px` (2-column grid, compact spacing)")
        lines.append("  - Desktop: `> 1024px` (3/4-column layouts, expanded desktop menu, full multi-pane views)")
        lines.append("- **Touch Optimization**: Tap targets minimum `44px x 44px`, zero horizontal overflow (`overflow-x: hidden`).\n")

        # 13. Interaction Requirements
        lines.append("## 13. Interaction Requirements")
        lines.append("- **Form Validation**: Instant inline feedback with `:user-valid` / `:user-invalid` styling.")
        lines.append("- **Hover States**: Transform scale (`1.02`), subtle box-shadow transition (`0.2s ease-out`).")
        lines.append("- **Drawer / Modal Overlays**: Keyboard `Escape` dismiss, focus trap, and background scroll lock.\n")

        # 14. Animation Guidelines
        lines.append("## 14. Animation Guidelines")
        lines.append("- **Motion Library**: Tailwind transitions / lightweight CSS keyframes or Framer Motion.")
        lines.append("- **Duration**: Micro-interactions `150ms - 200ms`, section reveals `350ms - 500ms`.")
        lines.append("- **Easing**: `cubic-bezier(0.16, 1, 0.3, 1)` for snappy, modern feel.")
        lines.append("- **Reduced Motion**: Respect `@media (prefers-reduced-motion: reduce)` with zero layout shifts.\n")

        # 15. Accessibility Requirements
        lines.append("## 15. Accessibility Requirements (WCAG 2.1 AA Compliance)")
        lines.append("- **Semantic Tags**: Pure HTML5 (`<header>`, `<nav>`, `<main>`, `<article>`, `<footer>`).")
        lines.append("- **Alt Attributes**: Descriptive `alt` text for all informative images; `aria-hidden=\"true\"` for decorative SVGs.")
        lines.append("- **Color Contrast**: Minimum `4.5:1` for normal text and `3:1` for large text and UI components.")
        lines.append("- **Keyboard Navigation**: Clear visible `:focus-visible` outline states on all interactive elements.\n")

        # 16. Development Recommendations
        lines.append("## 16. Development Recommendations for Coding Agent")
        lines.append("- **Recommended Framework**: React 18+ / Next.js or Vite with Tailwind CSS.")
        lines.append("- **Icon System**: Lucide Icons (`lucide-react`) for clean, consistent geometric line icons.")
        lines.append("- **Component Structure**: Modular atomic components in `src/components/`.")
        lines.append("- **Package Management**: Follow global rules (`pnpm` by default).")
        lines.append("- **Pre-implementation Verification**: Verify layout against the selected references before submitting final deliverables.")

        spec_content = "\n".join(lines)
        return spec_content
